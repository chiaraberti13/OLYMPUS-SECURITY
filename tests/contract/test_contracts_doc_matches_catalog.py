"""Every contract documented as canonical must actually be published.

``docs/contracts.md`` is the human-facing wire/storage compatibility policy and
its "Canonical contracts" table promises that "the authoritative JSON Schemas
are generated by ``olympus core export-schemas``". If a row names a contract that
is *not* in the published catalog, that promise is false — exactly the drift that
let ``olympus.apollo-rule`` be documented as canonical while missing from the
catalog. This gate pins the invariant: documented canonical contract ⇒ published.
"""

from __future__ import annotations

import re
from pathlib import Path

from olympus.schema_catalog import PUBLISHED_CONTRACTS

ROOT = Path(__file__).resolve().parents[2]
CONTRACTS_DOC = ROOT / "docs/contracts.md"

# ``olympus.custody`` is documented but deliberately not a single published model:
# it is a multi-version ledger (V1/V2) with signed wrappers in
# ``olympus.minerva.custody`` that does not map to one Pydantic schema. Its
# schemas ship with Minerva, not the generic catalog. Any OTHER documented
# canonical contract must be published.
_DOCUMENTED_BUT_NOT_IN_GENERIC_CATALOG = {"olympus.custody"}

_TABLE_NAME = re.compile(r"`(olympus\.[a-z0-9.-]+)`")


def _documented_canonical_contracts() -> list[str]:
    names: list[str] = []
    for line in CONTRACTS_DOC.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) < 3:
            continue
        match = _TABLE_NAME.fullmatch(cells[1])
        if match is not None:
            names.append(match.group(1))
    return names


def test_documented_canonical_contracts_are_published() -> None:
    documented = _documented_canonical_contracts()
    assert documented, "the canonical contracts table could not be parsed"

    published = {contract.name for contract in PUBLISHED_CONTRACTS}
    expected_published = set(documented) - _DOCUMENTED_BUT_NOT_IN_GENERIC_CATALOG
    missing = sorted(expected_published - published)
    assert not missing, (
        f"docs/contracts.md names these contracts as canonical but they are not "
        f"published in the schema catalog: {missing}"
    )

    # Anchor the regression this gate was written for.
    assert "olympus.apollo-rule" in published
    assert "olympus.apollo-rule" in documented


def test_custody_exclusion_stays_honest() -> None:
    # If custody ever becomes a single published model, drop it from the carve-out
    # so the forward invariant covers it too.
    published = {contract.name for contract in PUBLISHED_CONTRACTS}
    assert "olympus.custody" not in published, (
        "olympus.custody is now published; remove it from the documented carve-out "
        "in this test so the doc↔catalog invariant covers it"
    )
